let language: UiLanguage = 'en';

export function uiLanguage(): UiLanguage { return language; }

export function t(key: Key, params?: Readonly<Record<string, string | number>>): string {
  const template = language === 'zh-CN' ? ZH[key] : EN[key];
  if (!params) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

function translateOwnText(element: Element, key: Key): void {
  const translated = t(key);
  if (element.childElementCount === 0) {
    element.textContent = translated;
    return;
  }
  const ownText = [...element.childNodes].find(
    (node) => node.nodeType === 3 && (node.textContent?.trim().length ?? 0) > 0
  );
  if (ownText) ownText.textContent = translated;
}

export function applyDataI18n(root: ParentNode = document): void {
  for (const element of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = element.dataset.i18n as Key | undefined;
    if (key && Object.hasOwn(EN, key)) translateOwnText(element, key);
  }
  for (const element of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const key = element.dataset.i18nTitle as Key | undefined;
    if (key && Object.hasOwn(EN, key)) element.title = t(key);
  }
  for (const element of root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]')) {
    const key = element.dataset.i18nAriaLabel as Key | undefined;
    if (key && Object.hasOwn(EN, key)) element.setAttribute('aria-label', t(key));
  }
  for (const element of root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>('[data-i18n-placeholder]')) {
    const key = element.dataset.i18nPlaceholder as Key | undefined;
    if (key && Object.hasOwn(EN, key)) element.placeholder = t(key);
  }
}

export function setUiLanguage(
  preference: UiLanguagePreference,
  preferredSystemLanguages: readonly string[]
): UiLanguage {
  language = resolveUiLanguage(preference, preferredSystemLanguages);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
    applyDataI18n(document);
  }
  return language;
}

