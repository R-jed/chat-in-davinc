  function isSimplifiedChineseLocale(locale) {
    const normalized = String(locale || '').trim().replaceAll('_', '-');
    if (!normalized) return false;
    try {
      const parsed = new Intl.Locale(normalized);
      if (parsed.language.toLowerCase() !== 'zh') return false;
      const script = parsed.script && parsed.script.toLowerCase();
      if (script === 'hant') return false;
      if (script === 'hans') return true;
      const region = parsed.region && parsed.region.toUpperCase();
      if (region === 'TW' || region === 'HK' || region === 'MO') return false;
      if (region === 'CN' || region === 'SG') return true;
      return parsed.maximize().script?.toLowerCase() === 'hans';
    } catch {
      return false;
    }
  }

  function resolveLanguage(preference, preferredSystemLanguages) {
    if (preference === 'en' || preference === 'zh-CN') return preference;
    const languages = Array.isArray(preferredSystemLanguages)
      ? preferredSystemLanguages
      : Array.isArray(globalThis.navigator?.languages)
        ? globalThis.navigator.languages
        : [globalThis.navigator?.language || ''];
    const first = languages.find((locale) => String(locale || '').trim());
    return first && isSimplifiedChineseLocale(first) ? 'zh-CN' : 'en';
  }

  function text(language, key, params) {
    const dictionary = language === 'zh-CN' ? ZH_CN : EN;
    const template = dictionary[key] || EN[key] || key;
    if (!params) return template;
    return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
    );
  }

  globalThis.CLF_I18N = Object.freeze({ LANGUAGE_KEY, resolveLanguage, text });
